def L(narr, sub):
    a, b = narr.split(' / '), sub.split(' / ')
    assert len(a) == len(b), (narr, sub)
    out = []
    for p in b:
        t = re.sub(r' +', ' ', re.sub(r',\s*', ' ', p)).replace('?', '').strip()
        for k in ('만 원', '억 원'): t = t.replace(k, k.replace(' ', ' '))
