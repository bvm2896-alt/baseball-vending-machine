# 호흡(/) 합치기 규칙 — 문장 끝(요·다·죠·?)과 '제 생각엔·하지만·반대로·다만·그런데…' 앞의 쉼은 그대로 둔다.
# 합치는 순서(합쳐도 22자 이하일 때만): ① 꾸밈말·목적어·부사격(-ㄴ/-ㄹ/을/를/로/게) + 뒤 말 → ② 연결어미(-고/-며/-면/-서…) + 짧은 말(7자 이하)
#   → ③ 부사격 조사(에/에서/까지/와/의/엔…) + 뒤 말 → ④ 주어·주제(이/가/은/는/도) + 짧은 서술어(7자 이하). 훅 0·1줄(사용자 문구)은 그대로.
import re as _re
_L = lambda x: len(_re.sub(r'[\s,?·]', '', x))
_END = _re.compile(r'(요|다|죠|\?)$')
_ADN = _re.compile(r'(던|다는|라는|하는|되는|있는|없는|나는|오는|가는|보는|주는|받는|치는|쓰는|원하는|않는|싶은|않은|받은|맡은|가진|들어온|돌아온|채운|데려온|말한|합류한|정한|준|친|쓴|뛴|온|간|진|낸|른|된|한|할|될|을|를|로|으로|게|처럼|보다)$')
_CONN = _re.compile(r'(고|며|면|면서|지만|는데|은데|서|니까|어|아|해|쳐|하며)$')
_P2 = _re.compile(r'(에|에서|에게|께|까지|부터|와|과|의|만|엔|에선|론)$')
_SUBJ = _re.compile(r'(이|가|은|는|도)$')
_START = _re.compile(r'^(제 생각엔|하지만|반대로|다만|그런데|그래서|게다가|대신)')
def _cls(a, b):
    if _END.search(a) or _START.search(b): return 9
    if _ADN.search(a): return 1
    if a.endswith(('에서', '에선')): return 3
    if _CONN.search(a): return 2 if _L(b) <= 7 else 9
    if _P2.search(a): return 3
    if _SUBJ.search(a): return 4 if _L(b) <= 7 else 9
    return 9
def _plan(seg, nseg):
    G = [[k] for k in range(len(seg))]; tx = lambda g: ' '.join(seg[k] for k in g); nx = lambda g: ' '.join(nseg[k] for k in g)   # 읽는 대사(한글 숫자)도 22자 이하
    for c in (1, 2, 3, 4):
        ch = True
        while ch:
            ch = False
            for j in range(len(G) - 1):
                a, b = tx(G[j]), tx(G[j + 1])
                if _cls(a, b) == c and _L(a + b) <= 22 and _L(nx(G[j]) + nx(G[j + 1])) <= 22:
                    G[j] = G[j] + G[j + 1]; del G[j + 1]; ch = True; break
    return G
