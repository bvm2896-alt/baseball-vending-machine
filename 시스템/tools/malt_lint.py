# 말투 금지 검사 (11/14 사용자 "내가 교정을 아무리 해줘도 바뀌질 않냐") — 콘티를 PC에 넣기 전에 반드시 돌린다. 하나라도 걸리면 넣지 않는다.
# 사용자가 지적한 말투를 '종류'로 막는다. 새 지적이 나오면 여기에 한 줄 더한다.
import json, re, sys
BAN = [
 (r'(보상|부담|대가)이 (가장|훨씬|조금|더) (커요|줄어요|적죠|적어요|커지죠)', '다 아는 요약(11/14 16:33)'),
 (r'당연히', '다 아는 말(16:33)'),
 (r'이런 (말|글|얘기|전망|반응|분석|평가)', '예고 줄(11:47·11:57)'),
 (r'(글이|글도) 올라', "'글이 올라왔어요'(11:47) → '반응이에요'"),
 (r'뜻밖의', '예고 줄(12:00)'),
 (r'하나 더', '예고 줄'),
 (r'상황이 (좀 |조금 )?달라요|사정이 달라요', '미리 요약(12:00)'),
 (r'(마음이 급해요|입지가 좁아|눈에 띄어요|분명해요)$', '미리 요약(12:00)'),
 (r'^돈은 (어떨까요|넉넉할까요|있어요|넉넉해요)', '예고 줄(17:13)'),
 (r'(숫자|수치|상황|모습|선택|입장|분위기)(이에요|예요|이었죠|였죠|이죠)', "명사로 감싼 끝맺음(11:47 '가장 많은 숫자예요')"),
 (r'등급으로 봐요', "'C등급으로 봐요' ✗ → 'C등급이에요'(17:13)"),
 (r'(얘기였죠|한 거예요|라는 거죠|다는 거죠|는 거예요)$', '말 다시 감싸기(11:47)'),
 (r'보호선수 \d+명 (외|밖)', '설명 없는 전문 용어(17:08)'),
 (r'반쪽|가벼워요|조용해요|숙제는|의 겨울은', '빗댄 포장(08:04)'),
 (r'(먼저|이제) .*볼게요$|부터 볼게요$|같이 볼게요$', '예고 줄(14:11)'),
 (r'^(또한|따라서|이를 통해)', '번역투 접속사(08:07)'),
]
def check(epf):
    ep = json.load(open(epf, encoding='utf8')); bad = []
    for i, l in enumerate(ep['lines']):
        if l.get('pinned') or '구독' in l['sub']: continue
        for b in l['sub'].replace('\n', ' ').split('|'):
            b = b.strip()
            for p, why in BAN:
                if re.search(p, b): bad.append((i, b, why))
    return bad
if __name__ == '__main__':
    bad = check(sys.argv[1])
    for i, b, why in bad: print(f'{i:3d} | {b} | {why}')
    print(f'말투 금지 걸림 {len(bad)}곳'); sys.exit(1 if bad else 0)
