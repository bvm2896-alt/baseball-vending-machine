def wrap16(s, n=16):
    """자막 한 조각을 16자 안쪽 두 줄로(낱말 단위)"""
    if '\n' in s or len(s) <= n: return s
    w = s.split(' '); best = None
    for k in range(1, len(w)):
        a, b = ' '.join(w[:k]), ' '.join(w[k:])
        sc = max(len(a), len(b))
        if re.match(r'^(게|것|수|달러|원|점|개|번|명|위|년|월|일|경기|퍼센트)', b) or re.search(r'\d$', a): sc += 20
        if len(a) > n or len(b) > n: sc += 5
        if best is None or sc < best[0]: best = (sc, a + '\n' + b)
    return best[1]

def NEW(narr, sub, scene):
    pcs = [wrap16(x) for x in sub.split('|')]
    assert len(pcs) == len(narr.split(' / ')), (narr, sub)
    return (None, {'narr': narr, 'sub': '|'.join(pcs)}, scene)

def _shift(sc, key, d):
    """장면 복사본에서 key 목록의 at 를 d 만큼 옮긴다(호흡을 지운 줄에 맞춤)."""
    sc = copy.deepcopy(sc)
    for it in sc.get(key, []):
        if it.get('at') is not None: it['at'] = it['at'] + d
    return sc

def OLD(i, scene=None, narr=None, sub=None, rep=None):
    """롱폼 i번 줄 그대로(음성 재사용). rep=[(a,b)] 면 나레이션·자막을 치환(→ 그 줄만 새로 합성)."""
    d = copy.deepcopy(LN[i])
    for k in ('pace', 'gapAfter'): d.pop(k, None)   # 컷 쇼츠는 1.2배 한 속도(완급 없음)
    if rep:
        for a, b in rep: d['narr'] = d['narr'].replace(a, b); d['sub'] = d['sub'].replace(a, b)
    if narr: d['narr'] = narr
    if sub: d['sub'] = '|'.join(wrap16(x) for x in sub.split('|'))
    assert len(d['sub'].split('|')) == len(d['narr'].split(' / ')), (i, d)
    sc = copy.deepcopy(scene if scene is not None else SCN.get(i))
    changed = bool(rep or narr)
    return (i if not changed else None, d, sc)

