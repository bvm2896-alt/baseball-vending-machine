"""10/20 롱폼㉑ 나레이션 앞·뒤처리 (gen_1015 narr_of 전후)."""
import re
AGE = {'45살': '마흔다섯 살', '38살': '서른여덟 살', '39살': '서른아홉 살', '33살': '서른세 살', '29살': '스물아홉 살',
       '22살': '스물두 살', '24살': '스물네 살', '26살': '스물여섯 살', '35살': '서른다섯 살', '25살': '스물다섯 살'}
NAT1 = ['', '한', '두', '세', '네', '다섯', '여섯', '일곱', '여덟', '아홉']
NAT10 = ['', '열', '스물', '서른', '마흔', '쉰', '예순', '일흔', '여든', '아흔']
def nat(n):
    """1~99 → 고유어 관형 수사(단위 앞): 1 한, 20 스무, 25 스물다섯"""
    if n == 20: return '스무'
    return NAT10[n // 10] + NAT1[n % 10]
def pre(t):
    # 10/24: 고정 바꾸기는 숫자 중간에 걸리지 않게(앞이 숫자면 안 바꿈) — '2026시즌'이 '202+6시즌 → 이백이여섯 시즌'이 되던 사고
    for a, b in list(AGE.items()) + [('6개월', '육 개월'), ('4개월', '사 개월'), ('2주', '이 주'), ('3곳', '세 곳'),
                                     ('120경기', '백이십 경기'), ('297경기', '이백구십칠 경기'), ('54경기', '오십사 경기')]:
        t = re.sub(r'(?<![\d.,])' + re.escape(a), b, t)
    # 10/24 읽기 사전(tools/read_dict.json): 시즌을 세는 수(1~99)는 고유어(한 시즌·일곱 시즌), 연도+시즌(2026시즌)은 한자어 / % → 퍼센트
    t = re.sub(r'(?<![\d.,])([1-9]\d?)시즌', lambda m: nat(int(m.group(1))) + ' 시즌', t)
    t = re.sub(r'(\d)%', r'\1퍼센트', t)
    t = re.sub(r'(\d+)(라운드|홀드)', lambda m: m.group(1) + ' ' + m.group(2), t)
    t = re.sub(r'(\d)군', r'\1 군', t)
    # 10/24 사용자 지적("일곱번이 아니라 칠번타자잖아"): 타순·포지션 앞 'N번'은 한자어로 읽는다(7번 좌익수 → 칠번 좌익수, 4번 타자 → 사번 타자)
    SINO = dict(zip('123456789', '일이삼사오육칠팔구'))
    POS = r'(타자|타순|좌익수|우익수|중견수|지명타자|1루수|2루수|3루수|유격수|포수|투수|일루수|이루수|삼루수|선발|자리|배번)'
    t = re.sub(r'(?<![\d])([1-9])번(?= ?' + POS + ')', lambda m: SINO[m.group(1)] + '번', t)          # 7번 좌익수 → 칠번 좌익수
    t = re.sub(r'(등번호|배번) ?([1-9])번', lambda m: m.group(1) + ' ' + SINO[m.group(2)] + '번', t)   # 등번호 6번 → 등번호 육번
    t = re.sub(r'(?<![\d])([1-9])번(?=(으로|에서|에) ?(나왔|나서|출전|배치|기용|선발))', lambda m: SINO[m.group(1)] + '번', t)   # 7번으로 출전 → 칠번으로 출전
    t = t.replace('KBO', '케이비오').replace('FA', '에프에이').replace('SNS', '에스엔에스')
    return t
def post(t):
    t = t.replace('육 월', '유월').replace('십 월', '시월')
    return t
