def school_short(s):
    s = s.replace('(얼리)', '')
    if 'MLB' in s: return '울산 웨일즈'
    return s.split('-')[-1]
def pos_short(p): return {'투타겸업': '투수·타자'}.get(p, p)

def card(p):
    sc = school_short(p['school'])
    return {'badge': f"{p['rd']}R · {p['pick']}번", 'name': p['name'], 'sub': f"{sc} · {pos_short(p['pos'])}"}

def roster_scene(team, text):
    ps = D['teams'][team]
    pit = [p for p in ps if p['pos'] in ('투수', '투타겸업')]
    bat = [p for p in ps if p['pos'] not in ('투수', '투타겸업')]
    def pane(name, arr):
        return {'team': team, 'name': name, 'label': f'{len(arr)}명', 'groups': [{'k': f"{p['rd']}R", 'v': p['name']} for p in arr]}
    return {'type': 'roster', 'title': f'{FULL[team]} 2027 신인 전체', 'left': pane('투수', pit), 'right': pane('야수', bat), 'text': text, 'size': 64}

def steps_lines(team):
    """2R~ 를 3/3/나머지 로 나눠 (narr, sub, scene) 세 개"""
    ps = [p for p in D['teams'][team] if not (p['rd'] == 1)]
    chunks = [ps[0:4], ps[4:7], ps[7:]] if len(ps) == 10 else [ps[0:4], ps[4:8], ps[8:]] if len(ps) == 11 else [ps[0:3], ps[3:6], ps[6:]]
    out = []
    for ch in chunks:
        parts = []
        for p in ch:
            sc = school_short(p['school'])
            spoken = {'투타겸업': '투수 겸 타자'}.get(p['pos'], p['pos'])
            if p['name'] == '최지만': parts.append('이 라운드는 그 최지만이에요')
            else: parts.append(f"{KN[p['rd']]} 라운드 {sc} {spoken} {p['name']}")
        narr = ' / '.join(parts)
        if not narr.endswith('에요') and not narr.endswith('예요'):
            narr += ('이에요' if (ord(narr[-1]) - 0xAC00) % 28 else '예요')
        sub = '|'.join(f"{p['rd']}R {p['name']}" for p in ch)
        out.append((narr, sub, {'type': 'cards', 'title': f"{ch[0]['rd']}~{ch[-1]['rd']}라운드", 'items': [card(p) for p in ch]}))
    return out

def big(text, size=96, **kw):
    s = {'type': 'big', 'text': text, 'size': size}; s.update(kw); return s

